def record_live_event(event_type: str, title: str, detail: str, icon: str, status: str, payment_id: Optional[str] = None, delay_ms: int = 0, technical: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
    pid = payment_id or "pay_005"
    tech_data = technical or {
        "traceId": f"tr_{pid}_{uuid.uuid4().hex[:6]}",
        "requestId": f"req_{uuid.uuid4().hex[:8]}",
        "endpoint": "/api/v1/payment-webhook",
        "httpStatus": 504 if "timeout" in detail.lower() or "504" in detail else 200,
        "latency": f"{int(time.time() * 100) % 80 + 35} ms",
        "idempotencyKey": f"{pid}_ORDER_SYNC_v1",
        "signatureStatus": "HMAC_SHA256_VERIFIED",
        "retryCount": 1
    }
    event = {
        "id": len(agent_live_event_history) + 1,
        "time": time.strftime("%H:%M:%S"),
        "timestamp_ms": int(time.time() * 1000),
        "type": event_type,
        "title": title,
        "detail": detail,
        "icon": icon,
        "status": status,
        "payment_id": payment_id,
        "delay": delay_ms,
        "technical": tech_data
    }
    agent_live_event_history.append(event)
    if len(agent_live_event_history) > 150:
        agent_live_event_history.pop(0)
    return event


