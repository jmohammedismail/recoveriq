def _analyze_uploaded_row(row: dict) -> tuple[str, str, bool]:
    """
    Evaluates an uploaded payment record row and returns:
    (display_status, recommendation, is_failed)
    """
    p_status = str(row.get("payment_status") or row.get("status") or "").strip().upper()
    r_status = str(row.get("recovery_status") or "").strip().upper()
    root_cause = str(row.get("root_cause") or row.get("problem") or row.get("failure_reason") or "").strip()
    decision = str(row.get("decision") or row.get("recommendation") or row.get("policy") or "").strip().upper()
    webhook = str(row.get("webhook_status") or "").strip().upper()

    # 1. Normal / No Failure detected (e.g. pay_008, pay_009, pay_010)
    if "NO FAILURE" in root_cause.upper() or "NONE" in root_cause.upper() or (p_status == "SUCCESS" and webhook == "DELIVERED" and not root_cause):
        return ("Success", "No Action", False)

    # 2. Already Recovered (e.g. pay_004 with recovery_status RECOVERED)
    if r_status in ("RECOVERED", "SUCCESS") or "ALREADY RECOVERED" in decision or "RECOVERED" in root_cause.upper():
        return ("Recovered", "Already Recovered", True)

    # 3. Duplicate Order Risk / Stop (e.g. pay_001)
    if "DUPLICATE" in root_cause.upper() or r_status == "STOPPED" or "DO NOT" in decision or "ALREADY EXISTS" in root_cause.upper():
        return ("Stopped", "Do Not Double-Charge", True)

    # 4. Critical Error / High Risk / Stop (e.g. pay_003, pay_007)
    if decision == "STOP" or "INTERNAL" in root_cause.upper() or "500" in root_cause or "SIGNATURE" in root_cause.upper() or r_status == "ESCALATED":
        return ("Failed", "Investigate / Safety Halt", True)

    # 5. Human Review (e.g. pay_002, pay_005, pay_006)
    if "HUMAN" in decision or "REVIEW" in decision or r_status == "PENDING" or "2/2" in root_cause:
        return ("Pending Review", "Human Review", True)

    # 6. Auto Recovery (e.g. missing order, safe retry)
    if "AUTO" in decision or "RECOVER" in decision or "MISSING" in root_cause.upper():
        return ("Recoverable", "Auto Recovery", True)

    # 7. Gateway / Webhook Timeout fallback
    if "TIMEOUT" in root_cause.upper() or "504" in root_cause:
        return ("Failed", "Auto Recovery" if p_status == "SUCCESS" else "Retry Payment", True)

    if p_status in ("SUCCESS", "PAID", "COMPLETED") and not root_cause:
        return ("Success", "No Action", False)

    return ("Failed", "Review", True)

