def _check_and_record_idempotency(
    idempotency_key: str,
    payment_id: str,
    action: str,
    creator_fn
) -> Dict[str, Any]:
    """
    Atomically verifies and registers an idempotent action.
    - If duplicate: returns original execution payload with duplicate=True.
    - If conflict (key reused with different payment_id or action): raises 409 Conflict.
    - If new: creates execution record atomically, writes to store, and returns payload.
    """
    with idempotency_lock:
        store = load_json(IDEMPOTENCY_STORE_PATH)
        if not isinstance(store, dict):
            store = {}

        if idempotency_key in store:
            entry = store[idempotency_key]
            # Conflict check: key reused with DIFFERENT payment_id or incompatible action
            is_same_payment = (entry.get("payment_id") == payment_id)
            is_same_action = (entry.get("action") == action)
            is_compatible_approval = (
                is_same_payment and
                entry.get("action") in ("ORDER_SYNC", "RECOVERY_EXECUTION", "APPROVE_RECOVERY", "HUMAN_REVIEW_APPROVE", "IDEMPOTENCY_INTENT") and
                action in ("ORDER_SYNC", "RECOVERY_EXECUTION", "APPROVE_RECOVERY", "HUMAN_REVIEW_APPROVE", "IDEMPOTENCY_INTENT")
            )

            if not is_same_payment or (not is_same_action and not is_compatible_approval):
                logger.warning(
                    f"Idempotency key conflict detected for key '{idempotency_key}': "
                    f"existing=(payment_id={entry.get('payment_id')}, action={entry.get('action')}), "
                    f"incoming=(payment_id={payment_id}, action={action})"
                )
                raise HTTPException(
                    status_code=409,
                    detail={
                        "success": False,
                        "error": "IDEMPOTENCY_KEY_CONFLICT",
                        "message": "This idempotency key is already associated with another action."
                    }
                )

            # Duplicate match: return original response payload
            logger.info(
                f"Duplicate idempotent request detected for {payment_id} "
                f"(key: {idempotency_key}, exec: {entry.get('execution_id')})"
            )
            dup_res = dict(entry.get("response_payload", {}))
            dup_res["duplicate"] = True
            dup_res["message"] = "Duplicate request detected. Returning existing execution."
            return dup_res

        # New action execution creation
        payload = creator_fn()
        payload["duplicate"] = False

        store[idempotency_key] = {
            "idempotency_key": idempotency_key,
            "payment_id": payment_id,
            "action": action,
            "execution_id": payload.get("execution_id"),
            "incident_id": payload.get("incident_id"),
            "status": payload.get("status", "QUEUED"),
            "created_at": datetime.now(timezone.utc).isoformat(),
            "response_payload": payload
        }
        save_json(IDEMPOTENCY_STORE_PATH, store)

        logger.info(
            f"Idempotent action accepted for {payment_id} "
            f"(key: {idempotency_key}, exec: {payload.get('execution_id')})"
        )
        return payload

