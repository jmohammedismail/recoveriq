@app.post("/webhooks/ingest")
@app.post("/api/webhooks/ingest")
async def ingest_webhook_endpoint(request: Request):
    """
    Topic 2.1 - Authenticated Webhook Ingestion Endpoint.
    1. Reads EXACT raw request body bytes.
    2. Reads 'X-Webhook-Signature' header.
    3. Performs constant-time HMAC-SHA256 signature verification BEFORE payload processing.
    4. Rejects missing/invalid signatures with HTTP 401.
    5. Only processes payload if verification passes.
    """
    raw_body = await request.body()
    sig_header = request.headers.get("x-webhook-signature") or request.headers.get("x-signature")

    # Verify signature over RAW BYTES
    verification = verify_webhook_signature(raw_body, sig_header)

    if verification.get("status") == "CONFIGURATION_ERROR":
        raise HTTPException(status_code=500, detail=verification)

    if not verification.get("verified"):
        # HTTP 401 for missing or invalid signatures
        raise HTTPException(status_code=401, detail=verification)

    # Payload is authenticated - now safe to parse JSON
    payload = {}
    if raw_body:
        try:
            payload = json.loads(raw_body.decode("utf-8"))
        except Exception:
            raise HTTPException(status_code=400, detail="Malformed JSON in authenticated webhook body.")

    payment_id = payload.get("payment_id") or payload.get("id") or (payload.get("data", {}).get("payment_id") if isinstance(payload.get("data"), dict) else None)
    event_type = payload.get("event") or payload.get("type") or "payment.captured"

    record_live_event(
        "WEBHOOK_VERIFIED",
        "Gateway Webhook Verified",
        f"HMAC-SHA256 signature verified for {payment_id or 'event'} ({event_type})",
        "shield-check",
        "ok",
        payment_id
    )

    # Topic 2.2.2.12 — Automatic Recovery Integration with the Incident Pipeline
    auto_trigger_res = None
    if payment_id:
        try:
            from src.automatic_recovery_trigger import trigger_automatic_recovery_if_eligible
            auto_trigger_res = trigger_automatic_recovery_if_eligible(
                payment_id=payment_id,
                merchant_id=payload.get("merchant_id") or "merchant_demo",
                endpoint=payload.get("endpoint") or "payment-webhook",
                case_data=payload,
                webhook_verified=True,
                trigger_source="PAYMENT_INCIDENT_PIPELINE"
            )
        except Exception as trigger_err:
            import logging
            logging.getLogger("api_bridge").error(f"Downstream automatic recovery trigger error for {payment_id}: {trigger_err}")

    return {
        "status": "success",
        "verified": True,
        "payment_id": payment_id,
        "event": event_type,
        "automatic_recovery": auto_trigger_res
    }

